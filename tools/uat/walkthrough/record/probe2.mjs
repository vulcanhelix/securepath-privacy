import { chromium } from 'playwright';
const b = await chromium.launch({ headless: true });
const p = await (await b.newContext({ viewport: { width: 1600, height: 950 } })).newPage();
p.setDefaultTimeout(25000);
await p.goto('https://linear.app/login', { waitUntil: 'networkidle' }).catch(()=>{});
await p.waitForTimeout(4000);
await p.locator('button:has-text("Continue with email")').first().click();
await p.waitForTimeout(2000);
await p.screenshot({ path: 'step2-emailform.png' });
const email = p.locator('input[type="email"], input[name="email"], input[type="text"]').first();
console.log('email visible?', await email.count());
await email.fill('bruce@growthstrategy.co.za');
const cont = p.locator('button:has-text("Continue"), button[type="submit"]').first();
await cont.click();
await p.waitForTimeout(6000);
console.log('url after submit:', p.url());
await p.screenshot({ path: 'step3-afteremail.png', fullPage: true });
console.log('inputs now:', await p.locator('input').evaluateAll(e => e.map(x => ({t:x.type, ph:x.placeholder, ml:x.maxLength}))));
console.log('visible text sample:', (await p.locator('body').innerText()).slice(0, 600));
await b.close();
